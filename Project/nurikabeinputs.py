def check_grid(grid: Sequence[Sequence[int]]) -> None:
    """Perform sanity check on input grid."""
    nrow = len(grid)
    if nrow == 0:
        raise RuntimeError('Empty grid!')
    ncol = len(grid[0])
    for row in grid:
        if len(row) != ncol:
            raise RuntimeError('Non-rectangular grid!')
        for c in row:
            if c < -1 or c > nrow * ncol - 1:
                raise RuntimeError(f'Invalid clue ({c})!')

def find_clues(grid: Sequence[Sequence[int]]
               ) -> list[tuple[tuple[int,int],int]]:
    """Find the clues that are the roots of the islands."""
    nrow = len(grid)
    ncol = len(grid[0])
    return [((i,j),grid[i][j]) for i in range(nrow)
            for j in range(ncol) if grid[i][j] != 0]


